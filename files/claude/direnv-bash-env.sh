# Окружение direnv для инструмента Bash в Claude Code.
#
# Зачем. Штатный хук direnv висит на PROMPT_COMMAND и в неинтерактивном
# шелле не срабатывает вовсе, а сгенерированный Guix ~/.bashrc для таких
# шеллов делает `return 0` в самом начале — до files/bashrc дело тоже не
# доходит. Итог: Claude Code не видит программ из manifest.scm проекта.
#
# Подключается через CLAUDE_ENV_FILE, см. files/claude/settings.json.
#
# Почему именно CLAUDE_ENV_FILE, а не BASH_ENV. BASH_ENV bash читает при
# СТАРТЕ шелла, то есть раньше, чем Claude Code источит свой снимок
# (~/.claude/shell-snapshots/snapshot-bash-*.sh), а последняя строка того
# снимка — жёсткий `export PATH=…`. Проверено на t1: с BASH_ENV обычные
# переменные окружения доживали, а каталоги проекта из PATH исчезали, то
# есть ровно то, ради чего всё затевалось, не работало. CLAUDE_ENV_FILE
# источится ПОСЛЕ снимка, поэтому PATH здесь правится безнаказанно.
#
# Возвращать «хвост» PATH руками не нужно: на момент вызова каталоги из
# снимка (включая ~/.claude/plugins/…/bin) уже в PATH, direnv берёт их за
# свой «до» и сохраняет. Тоже проверено.
#
# Файл ИСТОЧАЕТСЯ, а не исполняется: shebang и бит +x не нужны, симлинк в
# стор подходит. `return` здесь не используем — неизвестно, в каком
# контексте Claude Code его источит, а вне функции и вне sourced-скрипта
# это ошибка.

if command -v direnv >/dev/null 2>&1; then
    eval "$(direnv export bash 2>/dev/null)"
fi
