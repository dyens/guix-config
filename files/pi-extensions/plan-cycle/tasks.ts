import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { lstat, mkdir, realpath, rename, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { randomUUID } from "node:crypto";
import { Type } from "typebox";
import { withFileMutationQueue, type ExtensionAPI, type ExtensionContext } from "@earendil-works/pi-coding-agent";
import { activeState, cycleContext, filePath, makeSnapshot, STATE, type CycleState } from "./core.ts";

export const TASKS = "plan-cycle-tasks-v1";
export interface Step {
	id: number;
	title: string;
	instruction: string;
	needs: number[];
	status: "pending" | "active" | "done" | "blocked" | "cancelled";
	result?: string;
	checks?: string;
	handoff?: string;
	startHead?: string;
	git?: { head: string; paths: string[]; committedPaths: string[]; truncated: boolean };
}
export interface Tasks {
	version: 1;
	planPath: string;
	context: string;
	notes: string;
	nextId: number;
	steps: Step[];
}
export function taskState(ctx: ExtensionContext): Tasks | undefined {
	const active = activeState(ctx.sessionManager.getBranch());
	if (active?.state.workflow !== "tasks") return;
	for (const entry of [...ctx.sessionManager.getBranch()].reverse()) {
		if (entry.type === "custom" && (entry.customType === TASKS || entry.customType === STATE)) {
			const state = entry.customType === TASKS ? entry.data as Tasks : (entry.data as CycleState).tasks;
			if (!state) throw new Error("Отсутствует состояние tasks на границе");
			if (state.version !== 1 || state.planPath !== active.state.planPath || typeof state.context !== "string" || typeof state.notes !== "string" ||
				!Number.isSafeInteger(state.nextId) || state.nextId < 1 || state.context.length > 6000 || state.notes.length > 4000 ||
				!Array.isArray(state.steps) || !state.steps.length || state.steps.length > 1000 ||
				state.steps.some(s => !Number.isInteger(s.id) || s.id < 1 || s.id >= state.nextId || typeof s.title !== "string" || typeof s.instruction !== "string" || !Array.isArray(s.needs) ||
					s.needs.length > 8 || s.needs.some(id => !Number.isInteger(id)) || !["pending", "active", "done", "blocked", "cancelled"].includes(s.status)) ||
				new Set(state.steps.map(s => s.id)).size !== state.steps.length || state.steps.filter(s => ["active", "blocked"].includes(s.status)).length > 1) throw new Error("Повреждено состояние tasks");
			validate(state);
			if (state.steps.some(s => s.status === "pending") && !current(state)) throw new Error("Потерян active шаг");
			return structuredClone(state);
		}
	}
	throw new Error("Отсутствует состояние tasks");
}
function current(state: Tasks) { return state.steps.find(s => s.status === "active" || s.status === "blocked"); }
function activate(state: Tasks) {
	if (current(state)) return;
	const step = state.steps.find(s => s.status === "pending");
	if (step) {
		if (step.needs.some(id => state.steps.find(s => s.id === id)?.status !== "done")) throw new Error(`Не завершены зависимости шага #${step.id}`);
		step.status = "active";
	}
}
export function status(state: Tasks) {
	const live = state.steps.filter(s => s.status !== "cancelled");
	const blocked = current(state)?.status === "blocked" ? " (blocked)" : "";
	return `Tasks: ${live.filter(s => s.status === "done").length}/${live.length}${blocked}. Plan: ${state.planPath}`;
}
export function taskContext(state: Tasks) {
	const step = current(state);
	const previous = [...state.steps].reverse().find(s => s.status === "done");
	const ids = new Set([...(step?.needs ?? []), ...(previous ? [previous.id] : [])]);
	const inputs = state.steps.filter(s => ids.has(s.id)).map(s => ({ id: s.id, result: s.result, checks: s.checks, handoff: s.handoff }));
	return [status(state), `Task contract (agent-recorded; original user instructions take precedence):\n${state.context}`,
		`Living notes (current decisions, open findings/gates/resources; not a diary):\n${state.notes || "—"}`,
		`Current step:\n${JSON.stringify(step ?? null)}`,
		`Inputs from completed steps:\n${JSON.stringify(inputs)}`,
		`Next steps:\n${JSON.stringify(state.steps.filter(s => s.status === "pending").slice(0, 3).map(s => ({ id: s.id, title: s.title })))}`,
		"Other steps/results are archived outside model context. Use task_get(id) only when needed. Completion of steps is NOT product acceptance.",
	].join("\n\n");
}
function planView(state: Tasks) {
	return `<!-- Generated by task tools. Session state is authoritative; do not edit this file. -->\n# Task plan\n\n${status(state)}\n\n${state.context}\n\n## Current notes\n${state.notes || "—"}\n\n## Steps\n` + state.steps.map(s =>
		`\n- ${s.status.toUpperCase()} #${s.id} ${s.title}\n${s.instruction ? `  ${s.instruction}\n` : ""}${s.needs.length ? `  Needs: ${s.needs.join(", ")}\n` : ""}${s.result ? `  Result: ${s.result}\n` : ""}${s.checks ? `  Checks: ${s.checks}\n` : ""}${s.handoff ? `  Handoff: ${s.handoff}\n` : ""}${s.git ? `  Git observed (not ownership/evidence): ${JSON.stringify(s.git)}\n` : ""}`).join("");
}
async function render(state: Tasks) {
	await withFileMutationQueue(state.planPath, async () => {
		await mkdir(dirname(state.planPath), { recursive: true });
		const temp = `${state.planPath}.${randomUUID()}.tmp`;
		try {
			await writeFile(temp, planView(state), { flag: "wx", mode: 0o600 });
			await rename(temp, state.planPath);
		} finally { await rm(temp, { force: true }); }
	});
}
const text = (maxLength: number) => Type.String({ minLength: 1, maxLength });
const stepSchema = Type.Object({ title: text(180), instruction: Type.Optional(text(1200)), needs: Type.Optional(Type.Array(Type.Integer({ minimum: 1 }), { maxItems: 8 })) });
function validate(state: Tasks) {
	if (!state.steps.length || state.steps.length > 1000) throw new Error("План должен содержать 1–1000 шагов");
	for (const [index, s] of state.steps.entries()) {
		if (s.status === "cancelled") continue;
		if (s.needs.some(id => !state.steps.slice(0, index).some(previous => previous.id === id && previous.status !== "cancelled"))) throw new Error(`Зависимость #${s.id} должна указывать на предыдущий неотменённый шаг`);
	}
}
async function gitObserved(cwd: string, from?: string): Promise<Step["git"]> {
	try {
		const run = promisify(execFile);
		const options = { cwd, timeout: 5000, maxBuffer: 1024 * 1024, encoding: "utf8" as const };
		const head = (await run("git", ["rev-parse", "HEAD"], options)).stdout.trim();
		const paths = (await run("git", ["status", "--porcelain=v1", "-z", "--untracked-files=normal"], options)).stdout.split("\0").filter(Boolean);
		const committedPaths = from && from !== head
			? (await run("git", ["diff", "--name-status", "--no-renames", from, head, "--"], options)).stdout.split("\n").filter(Boolean) : [];
		return { head, paths: paths.slice(0, 200), committedPaths: committedPaths.slice(0, 200), truncated: paths.length > 200 || committedPaths.length > 200 };
	} catch { return undefined; }
}

export function registerTasks(pi: ExtensionAPI, alone: (ctx: ExtensionContext, id: string) => unknown) {
	const result = (message: string) => ({ content: [{ type: "text" as const, text: message }], details: undefined });
	const requireState = (ctx: ExtensionContext) => {
		const state = taskState(ctx);
		if (!state) throw new Error("Сначала task_plan; существующий Markdown v2 продолжай старым протоколом, без скрытой миграции");
		return state;
	};
	async function persist(ctx: ExtensionContext, state: Tasks, boundary?: CycleState) {
		ctx.signal?.throwIfAborted();
		// A transition is ONE durable entry: no crash window between result and boundary.
		// In-step block/replan entries deliberately leave the context boundary untouched.
		if (boundary) pi.appendEntry(STATE, { ...boundary, tasks: state });
		else pi.appendEntry(TASKS, state);
		try { await render(state); return ""; }
		catch (error) { return `\nPlan view unavailable: ${String(error)}. Session state is saved; next task update retries export.`; }
	}
	async function boundary(ctx: ExtensionContext, state: Tasks, callId: string) {
		const active = activeState(ctx.sessionManager.getBranch())!;
		const branch = ctx.sessionManager.getBranch(), leaf = ctx.sessionManager.getLeafId();
		const projection = ctx.sessionManager.buildSessionProjection();
		await cycleContext({ messages: projection.messages.filter(m => m.role !== "system"), branch, projection, active, cwd: ctx.cwd });
		const snapshot = await makeSnapshot(branch, projection, active.state.checkpointId, ctx.cwd, state.planPath, taskContext(state), true);
		if (ctx.sessionManager.getLeafId() !== leaf) throw new Error("Сессия изменилась; переход отменён");
		return { ...active.state, snapshot, cycle: active.state.cycle + 1, skipToolCallId: callId };
	}
	pi.registerCommand("task_get_status", {
		description: "Show Tasks: done/total. Plan: path — no LLM call",
		handler: async (_args, ctx) => {
			try {
				const state = taskState(ctx);
				ctx.ui.notify(state ? status(state) : "Tasks: inactive. Plan: —", "info");
			} catch (error) { ctx.ui.notify(String(error), "error"); }
		},
	});
	pi.registerTool({ name: "task_plan", label: "Plan task", executionMode: "sequential",
		description: "Once after intake, before product edits: save original checkpoint and a sequential plan; first step starts automatically. Extension owns statuses and generated plan.md. Include tests, independent final review and agreed delivery gates. No separate start/next or manual Markdown edits.",
		parameters: Type.Object({ plan_path: text(1000), context: text(6000), steps: Type.Array(stepSchema, { minItems: 1, maxItems: 1000 }) }),
		async execute(id, params, signal, _update, ctx) {
			signal?.throwIfAborted();
			const call = alone(ctx, id) as { id: string };
			const branch = ctx.sessionManager.getBranch(), leaf = ctx.sessionManager.getLeafId();
			if (activeState(branch)) throw new Error("Plan-cycle уже включён; продолжи текущую задачу");
			if (branch.some(e => e.type === "custom" && e.customType === "ruclaw-work-cycle")) throw new Error("Legacy work-cycles: используй --legacy-cycles");
			if (!branch.some(e => e.type === "message" && e.message.role === "user")) throw new Error("Сначала задай исходную задачу");
			const checkpointId = branch[branch.findIndex(e => e.id === call.id) - 1]?.id;
			if (!checkpointId) throw new Error("Пустая история checkpoint");
			const cwd = await realpath(ctx.cwd);
			const state: Tasks = { version: 1, planPath: filePath(params.plan_path, cwd), context: params.context, notes: "", nextId: params.steps.length + 1,
				steps: params.steps.map((s, index) => ({ ...s, id: index + 1, instruction: s.instruction ?? "", needs: s.needs ?? [], status: "pending" })) };
			validate(state); activate(state);
			try { await lstat(state.planPath); throw new Error("Файл plan_path уже существует; выбери новый scratch path, не перезаписывай чужой план"); }
			catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
			current(state)!.startHead = (await gitObserved(cwd))?.head;
			const snapshot = await makeSnapshot(branch, ctx.sessionManager.buildSessionProjection(), checkpointId, cwd, state.planPath, taskContext(state), true);
			if (ctx.sessionManager.getLeafId() !== leaf) throw new Error("Сессия изменилась; start отменён");
			signal?.throwIfAborted();
			const warning = await persist(ctx, state, { version: 2, enabled: true, workflow: "tasks", cwd, planPath: state.planPath, checkpointId, cycle: 1, mode: "step", snapshot, skipToolCallId: id });
			return result(`План сохранён; первый шаг активен.${warning}`);
		},
	});
	pi.registerTool({ name: "task_get", label: "Get task detail", executionMode: "sequential",
		description: "Retrieve ONE archived step by ID only when its instructions/result are needed. Current step and relevant handoff are already in context. Not a routine startup action.",
		parameters: Type.Object({ id: Type.Integer({ minimum: 1 }) }),
		async execute(_id, params, _signal, _update, ctx) {
			const step = requireState(ctx).steps.find(s => s.id === params.id);
			if (!step) throw new Error("Неизвестный шаг");
			return result(JSON.stringify(step));
		},
	});
	pi.registerTool({ name: "task_complete", label: "Complete task step", executionMode: "sequential",
		description: "Call ALONE after finishing all tools/children. Atomically save a SHORT outcome, actual checks and next-step handoff, finish active step and reset to next. No report files required. notes replaces living decisions/open gates/resources (not history); retain unresolved items. Does not prove acceptance or grant permissions.",
		parameters: Type.Object({ id: Type.Integer({ minimum: 1 }), result: text(1000), checks: Type.Optional(text(1200)), handoff: Type.Optional(text(1500)), notes: Type.Optional(Type.String({ maxLength: 4000 })) }),
		async execute(id, params, signal, _update, ctx) {
			signal?.throwIfAborted(); alone(ctx, id);
			const state = requireState(ctx), step = current(state);
			if (!step || step.id !== params.id || step.status !== "active") throw new Error("Завершать можно только текущий active шаг; blocked сначала перепланируй");
			const leaf = ctx.sessionManager.getLeafId();
			step.status = "done"; step.result = params.result; step.checks = params.checks; step.handoff = params.handoff;
			step.git = await gitObserved(ctx.cwd, step.startHead);
			if (ctx.sessionManager.getLeafId() !== leaf) throw new Error("Сессия изменилась; completion отменён");
			if (params.notes !== undefined) state.notes = params.notes;
			activate(state);
			const following = current(state);
			if (following) following.startHead = step.git?.head;
			const next = await boundary(ctx, state, id);
			signal?.throwIfAborted();
			const warning = await persist(ctx, state, next);
			return result(`${current(state) ? "Шаг завершён; следующий активен." : "Все шаги завершены. Сверь обязательные gates; сообщи краткий итог. Не повторяй completion."}${warning}`);
		},
	});
	pi.registerTool({ name: "task_block", label: "Block current step", executionMode: "sequential",
		description: "Save blocker/partial work WITHOUT resetting debugging context. Resolve technical plan via task_replan; unresolved scope/authority belongs to user. No repeated retries.",
		parameters: Type.Object({ id: Type.Integer({ minimum: 1 }), reason: text(1500) }),
		async execute(id, params, signal, _update, ctx) {
			signal?.throwIfAborted(); alone(ctx, id);
			const state = requireState(ctx), step = current(state);
			if (!step || step.id !== params.id) throw new Error("Не текущий шаг");
			step.status = "blocked"; step.handoff = params.reason;
			return result(`BLOCKED: ${params.reason}${await persist(ctx, state)}`);
		},
	});
	pi.registerTool({ name: "task_replan", label: "Revise remaining steps", executionMode: "sequential",
		description: "Revise in SAME context, no reset. Supply ALL remaining steps in execution order; existing IDs retain partial handoff, omitted unfinished steps are cancelled with reason, new steps get fresh IDs. Completed history is immutable. Resolves blocked technical plan, not user scope/authority. Use after review to add fixes. No ceremonial replanning after each edit.",
		parameters: Type.Object({ reason: text(1000), steps: Type.Array(Type.Object({ ...stepSchema.properties, id: Type.Optional(Type.Integer({ minimum: 1 })) }), { minItems: 1, maxItems: 1000 }), notes: Type.Optional(Type.String({ maxLength: 4000 })) }),
		async execute(id, params, signal, _update, ctx) {
			signal?.throwIfAborted(); alone(ctx, id);
			const state = requireState(ctx), used = new Set<number>();
			const remaining: Step[] = params.steps.map(s => {
				const old = s.id === undefined ? undefined : state.steps.find(step => step.id === s.id);
				if (s.id !== undefined && (!old || old.status === "done" || old.status === "cancelled" || used.has(s.id))) throw new Error("ID должен указывать на уникальный незавершённый шаг");
				const stepId = old?.id ?? state.nextId++; used.add(stepId);
				return { ...old, id: stepId, title: s.title, instruction: s.instruction ?? old?.instruction ?? "", needs: s.needs ?? old?.needs ?? [], status: "pending" };
			});
			const archive = state.steps.filter(s => !used.has(s.id)).map(s => s.status === "done" || s.status === "cancelled" ? s : { ...s, status: "cancelled" as const, handoff: params.reason });
			state.steps = [...archive, ...remaining];
			if (params.notes !== undefined) state.notes = params.notes;
			validate(state); activate(state);
			const leaf = ctx.sessionManager.getLeafId(), active = current(state)!;
			if (!active.startHead) active.startHead = (await gitObserved(ctx.cwd))?.head;
			if (ctx.sessionManager.getLeafId() !== leaf) throw new Error("Сессия изменилась; replan отменён");
			signal?.throwIfAborted();
			return result(`План обновлён без сброса контекста. Текущий шаг: ${JSON.stringify(current(state))}${await persist(ctx, state)}`);
		},
	});
}
